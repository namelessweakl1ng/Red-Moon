package com.redmoon.vault.ui

import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import com.redmoon.vault.VaultModel
import org.json.JSONObject

@Composable
internal fun PasswordGenerator(v: VaultModel, dismiss: () -> Unit, use: (String) -> Unit) {
    var length by remember { mutableFloatStateOf(24f) }
    var lower by remember { mutableStateOf(true) }
    var upper by remember { mutableStateOf(true) }
    var digits by remember { mutableStateOf(true) }
    var symbols by remember { mutableStateOf(true) }
    var generated by remember { mutableStateOf("") }
    AlertDialog(
        onDismissRequest = dismiss,
        title = { Text("A stronger password") },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("Length: ${length.toInt()}")
                Slider(length, { length = it }, valueRange = 12f..64f, steps = 51)
                listOf(
                        Triple("Lowercase", lower, { checked: Boolean -> lower = checked }),
                        Triple("Uppercase", upper, { checked: Boolean -> upper = checked }),
                        Triple("Numbers", digits, { checked: Boolean -> digits = checked }),
                        Triple("Symbols", symbols, { checked: Boolean -> symbols = checked }),
                    )
                    .forEach { (label, checked, change) ->
                        Row {
                            Checkbox(checked, change)
                            Text(label, Modifier.padding(top = 12.dp))
                        }
                    }
                Text(
                    if (generated.isBlank()) "Generate a unique password for this account."
                    else "Password ready · ${generated.length} characters",
                    style = MaterialTheme.typography.bodySmall,
                )
                OutlinedButton(
                    onClick = {
                        v.run(
                            request("generate")
                                .put(
                                    "options",
                                    JSONObject()
                                        .put("length", length.toInt())
                                        .put("lowercase", lower)
                                        .put("uppercase", upper)
                                        .put("digits", digits)
                                        .put("symbols", symbols),
                                )
                        ) {
                            generated = it.payload().getString("password")
                        }
                    },
                    enabled = !v.busy && (lower || upper || digits || symbols),
                    modifier = Modifier.fillMaxWidth(),
                ) {
                    Text("Generate")
                }
            }
        },
        confirmButton = {
            TextButton(
                onClick = {
                    use(generated)
                    generated = ""
                },
                enabled = generated.isNotBlank() && !v.busy,
            ) {
                Text("Use password")
            }
        },
        dismissButton = {
            TextButton(
                onClick = {
                    generated = ""
                    dismiss()
                }
            ) {
                Text("Cancel")
            }
        },
    )
}
